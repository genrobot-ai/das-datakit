def _prepare_hand_meshes(annotations: dict[str, Any], runtime_dir: Path | None = None) -> dict[str, int]:
    records = annotations["hands"]
    todo: dict[str, list[tuple[dict[str, Any], Any]]] = {"left": [], "right": []}
    for pair in records.values():
        for side in ("left", "right"):
            record = pair.get(side)
            if not record:
                continue
            params = record.get("mano")
            if params is not None:
                todo[side].append((record, params))
            else:
                record["vertices"], record["faces"] = _proxy_hand_mesh(record["points"])
                record["mesh_kind"] = "skeleton_proxy"
    if not any(todo.values()):
        model = None
        ManoParams = None
        mano_faces = None
    else:
        model, ManoParams, mano_faces = _load_mano_forward(runtime_dir)

    if model is not None:
        for side in ("left", "right"):
            items = todo[side]
            if not items:
                continue
            params = [ManoParams(
                item["global_transl"], item["global_orient"], item["hand_pose"], item["betas"],
                item["coordinate_frame"], item["rotation_representation"],
            ) for _record, item in items]
            vertices_batch, joints_batch = model.forward_batch(params, is_right=(side == "right"), return_vertices=True)
            for (record, _raw), vertices, model_joints in zip(items, vertices_batch, joints_batch):
                target_joints = record["points"]
                source_center = model_joints.mean(axis=0)
                target_center = target_joints.mean(axis=0)
                source = model_joints - source_center
                target = target_joints - target_center
                u, _singular, vt = np.linalg.svd(source.T @ target)
                rotation = u @ np.diag([1.0, 1.0, np.linalg.det(u @ vt)]) @ vt
                aligned_joints = source @ rotation + target_center
                rms = float(np.sqrt(np.mean(np.sum((aligned_joints - target_joints) ** 2, axis=1))))
                if rms <= 0.02:
                    record["vertices"] = (vertices - source_center) @ rotation + target_center
                    record["faces"] = mano_faces
                    record["mesh_kind"] = "mano"
                else:
                    record["vertices"], record["faces"] = _proxy_hand_mesh(target_joints)
                    record["mesh_kind"] = "skeleton_proxy"
    for pair in records.values():
        for record in pair.values():
            if not record or record.get("vertices") is not None:
                continue
            record["mesh_kind"] = "unavailable"
            counts["unavailable"] += 1
    counts = {"mano": 0, "skeleton_proxy": 0, "unavailable": 0}
    for pair in records.values():
        for record in pair.values():
            if not record:
                continue
            kind = record.get("mesh_kind", "unavailable")
            counts[kind] = counts.get(kind, 0) + 1
    return counts


def _make_tile(image: np.ndarray, camera: int, tile_w: int, tile_h: int) -> np.ndarray:
    if image is None or image.size == 0:
        tile = np.zeros((tile_h, tile_w, 3), np.uint8)
        text = f"camera{camera}: missing"
        cv2.putText(tile, text, (20, tile_h // 2), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (180, 180, 180), 2, cv2.LINE_AA)
        return tile
    scale = min(tile_w / image.shape[1], tile_h / image.shape[0])
    nw, nh = max(1, round(image.shape[1] * scale)), max(1, round(image.shape[0] * scale))
    resized = cv2.resize(image, (nw, nh), interpolation=cv2.INTER_AREA)
    tile = np.zeros((tile_h, tile_w, 3), np.uint8)
    y, x = (tile_h - nh) // 2, (tile_w - nw) // 2
    tile[y:y + nh, x:x + nw] = resized
    cv2.rectangle(tile, (0, 0), (tile_w - 1, tile_h - 1), (220, 220, 220), 2)
    cv2.putText(tile, f"camera{camera}", (15, 32), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (255, 255, 255), 3, cv2.LINE_AA)
    cv2.putText(tile, f"camera{camera}", (15, 32), cv2.FONT_HERSHEY_SIMPLEX, 0.9, (20, 20, 20), 1, cv2.LINE_AA)
    return tile


def _montage(images: dict[int, np.ndarray], tile_w: int = 640, tile_h: int = 520) -> np.ndarray:
    tiles = [_make_tile(images.get(c), c, tile_w, tile_h) for c in CAMERAS]
    return np.vstack([np.hstack(tiles[:3]), np.hstack(tiles[3:])])


class _H264:
    def __init__(self) -> None:
        import av
        self.codec = av.CodecContext.create("h264", "r")

    def decode(self, data: bytes) -> list[np.ndarray]:
        import av
        try:
            # MCAP writers use both Annex-B and four-byte length-prefixed AVC
            # packets.  PyAV accepts the former consistently across versions.
            if not (data.startswith(b"\x00\x00\x01") or data.startswith(b"\x00\x00\x00\x01")):
                out = bytearray()
                i = 0
                while i + 4 <= len(data):
                    n = int.from_bytes(data[i:i + 4], "big")
                    i += 4
                    if n <= 0 or i + n > len(data):
                        out.clear()
                        break
                    out.extend(b"\x00\x00\x00\x01")
                    out.extend(data[i:i + n])
                    i += n
                if out and i == len(data):
                    data = bytes(out)
            packet = av.packet.Packet(data)
            return [f.to_ndarray(format="bgr24") for f in self.codec.decode(packet)]
        except (av.error.InvalidDataError, EOFError):
            return []

    def flush(self) -> list[np.ndarray]:
        try:
            return [f.to_ndarray(format="bgr24") for f in self.codec.decode(None)]
        except Exception:
            return []


def _records(path: Path) -> Iterator[tuple[Any, Any, Any]]:
    with path.open("rb") as f:
        yield from NonSeekingReader(f).iter_messages()


def _preview_image(image: np.ndarray, max_width: int = 640) -> np.ndarray:
    """Keep decoded frames at montage resolution to bound preview memory."""
    if image.shape[1] <= max_width:
        return image
    scale = max_width / float(image.shape[1])
    return cv2.resize(image, (max_width, max(1, round(image.shape[0] * scale))), interpolation=cv2.INTER_AREA)


def _mcap_frames(path: Path, max_delta_ns: int, max_reference_frames: int | None = None) -> tuple[list[tuple[int, dict[int, np.ndarray]]], dict[int, Calibration], dict[str, Any]]:
    """Decode MCAP into synchronized six-view frames plus annotations."""
    cal: dict[int, Calibration] = {}
    images: dict[int, list[tuple[int, np.ndarray]]] = {c: [] for c in CAMERAS}
    hands: dict[int, dict[str, Any]] = {}
    poses: dict[int, np.ndarray] = {}
    decoders: dict[int, _H264] = {}
    reference_limit = None if max_reference_frames is None else max(1, int(max_reference_frames))
    for schema, channel, msg in _records(path):
        topic = str(channel.topic)
        if schema.name == "foxglove.CameraCalibration" and topic.endswith("/camera_info"):
            c = int(topic.split("camera")[1].split("/")[0])
            cal[c] = _calib_from_proto(CameraCalibration_pb2.CameraCalibration.FromString(msg.data))
        elif schema.name == "foxglove.PoseInFrame" and topic == "/robot0/vio/eef_pose":
            poses[int(msg.log_time)] = _pose_matrix(PoseInFrame_pb2.PoseInFrame.FromString(msg.data))
        elif schema.name == "foxglove.HandPointFrameInfo" and topic in ("/robot0/handtracking/left", "/robot0/handtracking/right"):
            t = int(msg.log_time)
            pair = hands.setdefault(t, {"left": None, "right": None})
            frame = HandTrackInfo_pb2.HandPointFrameInfo.FromString(msg.data)
            pair["left" if topic.endswith("/left") else "right"] = _decode_hand_record(frame)
        elif schema.name == "foxglove.CompressedImage" and "/compressed" in topic:
            c = int(topic.split("camera")[1].split("/")[0])
            if c not in images:
                continue
            m = CompressedImage_pb2.CompressedImage.FromString(msg.data)
            raw = bytes(m.data)
            if not raw:
                continue
            if raw[:3] == b"\xff\xd8\xff" or "jpeg" in str(m.format).lower():
                frame = cv2.imdecode(np.frombuffer(raw, np.uint8), cv2.IMREAD_COLOR)
                if frame is not None:
                    images[c].append((int(msg.log_time), _preview_image(frame)))
            else:
                decoder = decoders.setdefault(c, _H264())
                for frame in decoder.decode(raw):
                    images[c].append((int(msg.log_time), _preview_image(frame)))
            # Stop a short preview once every camera has enough decoded
            # packets.  The MCAP packet order puts hand/VIO messages before
            # camera packets for the same timestamp, so no annotation needed
            # by the final synchronized rows is lost here.
            if reference_limit is not None and all(len(images[k]) >= reference_limit for k in CAMERAS):
                break
    for c, decoder in decoders.items():
        # H264 flush frames belong to the final packet time; they are only a
        # fallback and do not affect normal synchronized frames.
        if images[c]:
            last_t = images[c][-1][0]
            images[c].extend((last_t, _preview_image(f)) for f in decoder.flush())
    if not cal:
        raise RuntimeError("MCAP contains no camera calibration topics")
    missing_calibrations = sorted(set(CAMERAS) - set(cal))
    if missing_calibrations:
        raise RuntimeError(f"MCAP is missing standard /camera_info calibrations for cameras {missing_calibrations}")
    ref = next((c for c in (2, 0, 3, 1, 4, 5) if images[c]), None)
    if ref is None:
        raise RuntimeError("MCAP contains no decodable camera images")
    ts_by_cam = {c: [x[0] for x in images[c]] for c in CAMERAS}
    frame_rows: list[tuple[int, dict[int, np.ndarray]]] = []
    for t, image in images[ref]:
        row = {ref: image}
        for c in CAMERAS:
            if c == ref or not images[c]:
                continue
            idx = bisect.bisect_left(ts_by_cam[c], t)
            candidates = [j for j in (idx - 1, idx) if 0 <= j < len(images[c])]
            if candidates:
                j = min(candidates, key=lambda k: abs(images[c][k][0] - t))
                if abs(images[c][j][0] - t) <= max_delta_ns:
                    row[c] = images[c][j][1]
        frame_rows.append((t, row))
        if reference_limit is not None and len(frame_rows) >= reference_limit:
            break
    return frame_rows, cal, {"hands": hands, "poses": poses}


def _project_mcap_frame(images: dict[int, np.ndarray], t: int, calibs: dict[int, Calibration], ann: dict[str, Any], max_delta_ns: int) -> dict[int, np.ndarray]:
    ht = _nearest(sorted(ann["hands"]), t, max_delta_ns)
    pt = _nearest(sorted(ann["poses"]), t, max_delta_ns)
    result = {c: image.copy() for c, image in images.items()}
    if ht is None or pt is None:
        return result
    pair, vio = ann["hands"][ht], ann["poses"][pt]
    for c, image in result.items():
        calib = calibs.get(c)
        if calib is None:
            continue
        T_world_camera = vio @ R_BODY_4 @ (calib.t_camera_to_base if calib.t_camera_to_base is not None else np.eye(4))
        T_camera_world = _invert(T_world_camera)
        scale = (image.shape[1] / calib.width if calib.width else 1.0, image.shape[0] / calib.height if calib.height else 1.0)
        for side in ("left", "right"):
            hand = pair.get(side)
            if hand is None:
                continue
            vertices = hand.get("vertices")
            if vertices is not None:
                camera_vertices = (T_camera_world[:3, :3] @ vertices.T + T_camera_world[:3, 3:4]).T
                _draw_projected_mesh(result[c], camera_vertices, hand["faces"], calib, side, scale)
            points = hand.get("points")
            if points is not None:
                camera_points = (T_camera_world[:3, :3] @ points.T + T_camera_world[:3, 3:4]).T
                uv, valid = project_ds_radtan(camera_points, calib)
                _draw(result[c], uv, valid, side, scale)
    return result


def render(*, output: Path, mcap: Path, max_frames: int | None = None, stride: int = 1,
           fps: float = 12.0, max_delta_ms: float = 100.0,
           mano_runtime_dir: Path | None = None) -> dict[str, Any]:
    output.parent.mkdir(parents=True, exist_ok=True)
    max_delta_ns = int(max_delta_ms * 1_000_000)
    frames_written = 0
    writer = None
    # Re-read image timestamps here so the association used for drawing is
    # exactly the same one as the six-view synchronization above.
    target = None if max_frames is None else max_frames * max(1, stride)
    frames, calibs, ann = _mcap_frames(mcap, max_delta_ns, target)
    mesh_counts = _prepare_hand_meshes(ann, mano_runtime_dir)
    for i, (t, image_set) in enumerate(frames):
        if i % max(1, stride):
            continue
        rendered = _project_mcap_frame(image_set, t, calibs, ann, max_delta_ns)
        montage = _montage(rendered)
        if writer is None:
            writer = cv2.VideoWriter(str(output), cv2.VideoWriter_fourcc(*"mp4v"), fps, (montage.shape[1], montage.shape[0]))
            if not writer.isOpened():
                raise RuntimeError(f"Could not open video writer: {output}")
        writer.write(montage)
        frames_written += 1
        if max_frames is not None and frames_written >= max_frames:
            break
    if writer is None:
        raise RuntimeError("No frames were rendered")
    writer.release()
    return {
        "output": str(output), "frames": frames_written, "fps": fps, "size": [1920, 1040],
        "calibration_topics": [f"/robot0/sensor/camera{c}/camera_info" for c in CAMERAS],
        "calibration_models": {str(c): calibs[c].model for c in CAMERAS},
        "hand_mesh_frames": mesh_counts,
    }


