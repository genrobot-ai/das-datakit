#!/usr/bin/env python3
"""Project left/right 21-joint hand skeletons from an MCAP to a six-view MP4.

The input MCAP must contain ``/robot0/handtracking/{left,right}``,
``/robot0/vio/eef_pose``, the six standard ``/camera_info`` calibration
topics and six compressed camera topics.  GT and alternate calibration topics
are ignored.  Both plain double-sphere (``ds``) and double-sphere plus
radial/tangential distortion (``ds-radtan``) calibrations are supported.

The projection convention is the one used by the dataset exporters:
``T_world_camera = T_vio @ R_BODY @ T_camera_to_base``.  Calibration values
are in native image pixels.  The output is a readable 3x2 montage (camera 0..2
on the first row, 3..5 on the second row), with a 30%-tint projected hand
surface, small unnumbered joints and a fine skeleton overlay.  When usable MANO parameters
are present, the surface is the reconstructed MANO mesh aligned to the
recorded joints.  For GT-only messages without MANO parameters, the script
builds a small surface proxy from those 21 joints.

Examples (run with the repository's Python environment)::

    python scripts/project_hand_keypoints_to_mp4.py \
      --mcap /root/workspace/2b4c28bf99fb4beca586d37b70e50b03_hand_mesh.mcap \
      --output /root/workspace/hand_projection_demo.mp4 --max-frames 180

    python scripts/project_hand_keypoints_to_mp4.py \
      --mcap /root/workspace/4df8f9338c7c4bd2bbaf3a4db6694d34-DAS-Ego_20260509174624_sub_center_de5c35_f546496b_with_gt.mcap \
      --output /root/workspace/ego_projection_demo.mp4 --max-frames 240 --fps 12
"""
