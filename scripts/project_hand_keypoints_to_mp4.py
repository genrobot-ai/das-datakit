@dataclass
class Calibration:
    fx: float
    fy: float
    cx: float
    cy: float
    xi: float
    alpha: float
    # k1, k2, k3, p1, p2 (the MCAP/PKL field order is k1,k2,k3,p1,p2)
    k1: float = 0.0
    k2: float = 0.0
    k3: float = 0.0
    p1: float = 0.0
    p2: float = 0.0
    width: int = 0
    height: int = 0
    model: str = "ds"
    t_camera_to_base: np.ndarray | None = None


def _as_float_array(value: Any, shape: tuple[int, ...] | None = None) -> np.ndarray:
    arr = np.asarray(value, dtype=np.float64)
    if shape is not None:
        arr = arr.reshape(shape)
    return arr


def _quat_to_matrix(q: Iterable[float]) -> np.ndarray:
    x, y, z, w = [float(v) for v in q]
    n = math.sqrt(x * x + y * y + z * z + w * w)
    if n < 1e-12:
        return np.eye(3, dtype=np.float64)
    x, y, z, w = x / n, y / n, z / n, w / n
    return np.array(
        [[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
         [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
         [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]],
        dtype=np.float64,
    )


def _pose_matrix(pose: Any) -> np.ndarray:
    """Read a pose dict or a protobuf PoseInFrame into a homogeneous matrix."""
    if pose is None:
        return np.eye(4, dtype=np.float64)
    if isinstance(pose, dict):
        pos = pose.get("translation", pose.get("position", pose.get("pos", [0, 0, 0])))
        quat = pose.get("rotation", pose.get("orientation", pose.get("quat", [0, 0, 0, 1])))
        if isinstance(pos, dict):
            pos = [pos.get(k, 0.0) for k in ("x", "y", "z")]
        if isinstance(quat, dict):
            quat = [quat.get(k, 0.0) for k in ("x", "y", "z", "w")]
    else:
        p = pose.pose if hasattr(pose, "pose") else pose
        pos = [p.position.x, p.position.y, p.position.z]
        quat = [p.orientation.x, p.orientation.y, p.orientation.z, p.orientation.w]
    out = np.eye(4, dtype=np.float64)
    out[:3, :3] = _quat_to_matrix(quat)
    out[:3, 3] = np.asarray(pos, dtype=np.float64)
    return out


def _camera_to_base(value: Any) -> np.ndarray:
    if value is None:
        return np.eye(4, dtype=np.float64)
    if isinstance(value, dict):
        if "matrix" in value:
            return _as_float_array(value["matrix"], (4, 4))
        t = value.get("translation", value.get("position", [0, 0, 0]))
        q = value.get("rotation", value.get("orientation", [0, 0, 0, 1]))
        out = _pose_matrix({"translation": t, "rotation": q})
        # Some generic PKLs call this transform camera_to_world.  The hand
        # dataset uses camera_to_base; retaining the field name makes the
        # intended direction explicit and avoids silently inverting it.
        return out
    arr = np.asarray(value, dtype=np.float64)
    if arr.size == 16:
        return arr.reshape(4, 4)
    if arr.size == 7:
        return _camera_to_base({"translation": arr[:3], "rotation": arr[3:]})
    raise ValueError(f"Unsupported camera transform with shape {arr.shape}")


def _calib_from_dict(value: dict[str, Any]) -> Calibration:
    d = list(value.get("distortion_params", value.get("D", value.get("distortion", []))))
    K = value.get("camera_K", value.get("K", []))
    if len(d) >= 6:
        fx, fy, cx, cy, xi, alpha = [float(x) for x in d[:6]]
    else:
        flat = np.asarray(K, dtype=np.float64).reshape(-1)
        if flat.size < 9:
            raise ValueError("Calibration needs six DS parameters or a 3x3 K")
        fx, fy, cx, cy = float(flat[0]), float(flat[4]), float(flat[2]), float(flat[5])
        xi, alpha = 0.0, 0.0
    # Canonical ds-radtan order is k1,k2,k3,p1,p2.  A few older PKLs have
    # only k1,k2,p1,p2,k3; explicit named fields, when present, win.
    k1 = float(value.get("k1", d[6] if len(d) > 6 else 0.0))
    k2 = float(value.get("k2", d[7] if len(d) > 7 else 0.0))
    k3 = float(value.get("k3", d[8] if len(d) > 8 else 0.0))
    p1 = float(value.get("p1", d[9] if len(d) > 9 else 0.0))
    p2 = float(value.get("p2", d[10] if len(d) > 10 else 0.0))
    return Calibration(
        fx, fy, cx, cy, xi, alpha, k1, k2, k3, p1, p2,
        int(value.get("width", 0)), int(value.get("height", 0)),
        str(value.get("distortion_model", value.get("model", "ds"))).lower(),
        _camera_to_base(value.get("camera_to_base", value.get("T_b_c"))),
    )


def _calib_from_proto(msg: Any) -> Calibration:
    d = list(msg.D)
    model = str(msg.distortion_model or "").strip().lower().replace("_", "-")
    model = {
        "ds-rt": "ds-radtan",
        "double-sphere": "ds",
        "double-sphere-radtan": "ds-radtan",
        "double-sphere-radial-tangential": "ds-radtan",
    }.get(model, model)
    expected = 6 if model == "ds" else 11 if model == "ds-radtan" else None
    if expected is None or len(d) != expected:
        raise ValueError(
            f"Unsupported camera model/parameter count: {msg.distortion_model!r}/{len(d)}; "
            "expected ds/6 or ds-radtan/11"
        )
    vals = [float(v) for v in d[:6]]
    # DS-RT order is fx,fy,cx,cy,xi,alpha,k1,k2,k3,p1,p2.
    extra = [float(v) for v in d[6:11]] if model == "ds-radtan" else [0.0] * 5
    t = list(msg.T_b_c)
    return Calibration(
        *vals, *extra[:5], int(msg.width), int(msg.height),
        model,
        _camera_to_base(t[:7]) if len(t) >= 7 else np.eye(4, dtype=np.float64),
    )


def _invert(T: np.ndarray) -> np.ndarray:
    R, t = T[:3, :3], T[:3, 3]
    out = np.eye(4, dtype=np.float64)
    out[:3, :3] = R.T
    out[:3, 3] = -(R.T @ t)
    return out


def project_ds_radtan(points_camera: np.ndarray, calib: Calibration) -> tuple[np.ndarray, np.ndarray]:
    """Project camera-frame XYZ into native distorted pixels.

    The valid domain follows the DS model used by the training runtime.  This
    function intentionally does not use cv2.fisheye: DS and DS-RT are distinct
    camera models.
    """
    xyz = np.asarray(points_camera, dtype=np.float64).reshape(-1, 3)
    x, y, z = xyz.T
    radius = np.linalg.norm(xyz, axis=1)
    zz = z + calib.xi * radius
    denom = calib.alpha * np.sqrt(x * x + y * y + zz * zz) + (1.0 - calib.alpha) * zz
    # DS has a camera-model domain in addition to a positive denominator.  The
    # latter alone accepts rays behind a fisheye camera for some xi/alpha
    # combinations and produces apparently plausible but wrong overlays.
    if calib.alpha <= 0.5:
        w1 = calib.alpha / max(1.0 - calib.alpha, 1e-12)
    else:
        w1 = (1.0 - calib.alpha) / max(calib.alpha, 1e-12)
    w2 = (w1 + calib.xi) / max(2.0 * w1 * calib.xi + calib.xi * calib.xi + 1.0, 1e-12) ** 0.5
    valid = (radius > 1e-8) & (z + w2 * radius > 1e-8) & np.isfinite(xyz).all(axis=1)
    qx = np.full(len(xyz), np.nan, dtype=np.float64)
    qy = np.full(len(xyz), np.nan, dtype=np.float64)
    qx[valid], qy[valid] = x[valid] / denom[valid], y[valid] / denom[valid]
    if "radtan" in calib.model:
        r2 = qx * qx + qy * qy
        radial = 1.0 + calib.k1 * r2 + calib.k2 * r2 * r2 + calib.k3 * r2 * r2 * r2
        tx = 2.0 * calib.p1 * qx * qy + calib.p2 * (r2 + 2.0 * qx * qx)
        ty = calib.p1 * (r2 + 2.0 * qy * qy) + 2.0 * calib.p2 * qx * qy
        qx, qy = qx * radial + tx, qy * radial + ty
    uv = np.stack([calib.fx * qx + calib.cx, calib.fy * qy + calib.cy], axis=1)
    return uv, valid


def _hand_points(value: Any) -> np.ndarray | None:
    """Extract standard hand joints in id order."""
    if value is None:
        return None
    # Keep a complete 21-point payload even when the producer's validity bit
    # is false.  Some hand-mesh demo MCAPs mark the frame invalid while still
    # carrying the fitted bones; an empty/short payload is still ignored below.
    if isinstance(value, dict):
        bones = value.get("bone_data", value.get("joints", value.get("keypoints", value.get("points"))))
    elif hasattr(value, "bone_data"):
        bones = value.bone_data
    else:
        bones = value
    if bones is None:
        return None
    arr = []
    bones = list(bones)
    if bones and hasattr(bones[0], "id"):
        bones = sorted((bone for bone in bones if int(bone.id) < 21), key=lambda bone: int(bone.id))
    elif bones and isinstance(bones[0], dict) and "id" in bones[0]:
        bones = sorted((bone for bone in bones if int(bone["id"]) < 21), key=lambda bone: int(bone["id"]))
    for bone in bones[:21]:
        if isinstance(bone, dict):
            p = bone.get("translation", bone.get("position", bone.get("xyz", bone.get("point"))))
            if p is None and "to_global" in bone:
                p = bone["to_global"].get("position", bone["to_global"])
        elif hasattr(bone, "to_global"):
            p = bone.to_global.position
        elif hasattr(bone, "position"):
            p = bone.position
        else:
            p = bone
        if isinstance(p, dict):
            p = [p.get(k, 0.0) for k in ("x", "y", "z")]
        elif hasattr(p, "x"):
            p = [p.x, p.y, p.z]
        a = np.asarray(p, dtype=np.float64).reshape(-1)
        if a.size < 3:
            return None
        arr.append(a[:3])
    if len(arr) < 21:
        return None
    return np.asarray(arr[:21], dtype=np.float64)


def _hand_mano_params(message: Any) -> dict[str, Any] | None:
    mano = getattr(message, "mano_params", None)
    if mano is None:
        return None
    try:
        params = {
            "global_transl": np.asarray(mano.global_transl, dtype=np.float64).reshape(3),
            "global_orient": np.asarray(mano.global_orient, dtype=np.float64).reshape(3, 3),
            "hand_pose": np.asarray(mano.hand_pose, dtype=np.float64).reshape(15, 3, 3),
            "betas": np.asarray(mano.betas, dtype=np.float64).reshape(10),
            "coordinate_frame": str(mano.coordinate_frame),
            "rotation_representation": str(mano.rotation_representation or "rotmat"),
        }
    except (TypeError, ValueError):
        return None
    arrays = (params["global_transl"], params["global_orient"], params["hand_pose"], params["betas"])
    if not all(np.isfinite(value).all() for value in arrays):
        return None
    if params["rotation_representation"].lower() not in ("rotmat", "rotation_matrix"):
        return None
    if params["coordinate_frame"] not in ("", "world_eef_pose"):
        return None
    return params


def _decode_hand_record(message: Any) -> dict[str, Any] | None:
    points = _hand_points(message)
    if points is None:
        return None
    return {"points": points, "mano": _hand_mano_params(message), "vertices": None, "mesh_kind": None}


def _nearest(sorted_times: list[int], t: int, max_delta: int) -> int | None:
    if not sorted_times:
        return None
    i = bisect.bisect_left(sorted_times, t)
    best = None
    dist = max_delta + 1
    for j in (i - 1, i):
        if 0 <= j < len(sorted_times) and abs(sorted_times[j] - t) < dist:
            best, dist = sorted_times[j], abs(sorted_times[j] - t)
    return best


def _draw(image: np.ndarray, points: np.ndarray, valid: np.ndarray, side: str, scale: tuple[float, float]) -> None:
    sx, sy = scale
    uv = points.copy()
    uv[:, 0] *= sx
    uv[:, 1] *= sy
    color = COLORS[side]
    h, w = image.shape[:2]
    def inside(p: np.ndarray) -> bool:
        return bool(np.isfinite(p).all() and 0 <= p[0] < w and 0 <= p[1] < h)
    for a, b in EDGES:
        if valid[a] and valid[b] and inside(uv[a]) and inside(uv[b]):
            pa, pb = tuple(np.round(uv[a]).astype(int)), tuple(np.round(uv[b]).astype(int))
            cv2.line(image, pa, pb, (0, 0, 0), 1, cv2.LINE_AA)
            cv2.line(image, pa, pb, color, 1, cv2.LINE_AA)
    for i, p in enumerate(uv):
        if not valid[i] or not inside(p):
            continue
        c = tuple(np.round(p).astype(int))
        cv2.circle(image, c, 2, (0, 0, 0), -1, cv2.LINE_AA)
        cv2.circle(image, c, 1, color, -1, cv2.LINE_AA)
    if valid[0] and inside(uv[0]):
        c = tuple(np.round(uv[0]).astype(int))
        label = "L" if side == "left" else "R"
        cv2.putText(image, label, (c[0] - 14, c[1] + 14), cv2.FONT_HERSHEY_SIMPLEX, 0.42, (0, 0, 0), 2, cv2.LINE_AA)
        cv2.putText(image, label, (c[0] - 14, c[1] + 14), cv2.FONT_HERSHEY_SIMPLEX, 0.42, color, 1, cv2.LINE_AA)


def _append_uv_sphere(vertices: list[list[float]], faces: list[list[int]], center: np.ndarray, radius: float,
                      rings: int = 4, segments: int = 7) -> None:
    base = len(vertices)
    for ring in range(rings + 1):
        phi = -0.5 * np.pi + np.pi * ring / rings
        cp, sp = np.cos(phi), np.sin(phi)
        for segment in range(segments):
            theta = 2.0 * np.pi * segment / segments
            vertices.append((center + radius * np.array([cp * np.cos(theta), cp * np.sin(theta), sp])).tolist())
    for ring in range(rings):
        for segment in range(segments):
            a = base + ring * segments + segment
            b = base + ring * segments + (segment + 1) % segments
            c = base + (ring + 1) * segments + (segment + 1) % segments
            d = base + (ring + 1) * segments + segment
            faces.extend(([a, b, c], [a, c, d]))


def _append_tapered_bone(vertices: list[list[float]], faces: list[list[int]], start: np.ndarray,
                         end: np.ndarray, radius_start: float, radius_end: float, segments: int = 7) -> None:
    axis = end - start
    length = float(np.linalg.norm(axis))
    if length < 1e-5:
        return
    axis /= length
    reference = np.eye(3)[int(np.argmin(np.abs(axis)))]
    u = np.cross(axis, reference)
    u /= max(float(np.linalg.norm(u)), 1e-12)
    v = np.cross(axis, u)
    base = len(vertices)
    for center, radius in ((start, radius_start), (end, radius_end)):
        for segment in range(segments):
            angle = 2.0 * np.pi * segment / segments
            offset = radius * (np.cos(angle) * u + np.sin(angle) * v)
            vertices.append((center + offset).tolist())
    for segment in range(segments):
        nxt = (segment + 1) % segments
        a, b = base + segment, base + nxt
        c, d = base + segments + nxt, base + segments + segment
        faces.extend(([a, b, c], [a, c, d]))


def _proxy_hand_mesh(points: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    """Build a lightweight tapered surface proxy when a GT stream has no MANO fit."""
    points = np.asarray(points, dtype=np.float64).reshape(21, 3)
    vertices: list[list[float]] = []
    faces: list[list[int]] = []
    radii = np.asarray((
        0.018, 0.014, 0.012, 0.009, 0.006,
        0.012, 0.010, 0.008, 0.006,
        0.013, 0.011, 0.009, 0.006,
        0.012, 0.010, 0.008, 0.006,
        0.010, 0.009, 0.007, 0.0055,
    ))
    for a, b in EDGES:
        _append_tapered_bone(vertices, faces, points[a], points[b], radii[a], radii[b])
    for index, point in enumerate(points):
        _append_uv_sphere(vertices, faces, point, float(radii[index]) * 0.9)

    # Approximate the palm web with a thin double-sided fan through the wrist
    # and the five metacarpal bases.
    boundary = points[[0, 1, 5, 9, 13, 17]]
    center = boundary.mean(axis=0)
    normal = np.cross(points[9] - points[0], points[5] - points[17])
    norm = float(np.linalg.norm(normal))
    if norm > 1e-8:
        normal *= 0.0045 / norm
    else:
        normal = np.array([0.0, 0.0, 0.0045])
    front = len(vertices)
    vertices.append((center + normal).tolist())
    back = len(vertices)
    vertices.append((center - normal).tolist())
    boundary_ids = (0, 1, 5, 9, 13, 17)
    for i, index in enumerate(boundary_ids):
        nxt = boundary_ids[(i + 1) % len(boundary_ids)]
        faces.append([front, index, nxt])
        faces.append([back, nxt, index])
    return np.asarray(vertices, dtype=np.float64), np.asarray(faces, dtype=np.int32)


def _mesh_edges(faces: np.ndarray) -> np.ndarray:
    edges = np.concatenate((faces[:, [0, 1]], faces[:, [1, 2]], faces[:, [2, 0]]), axis=0)
    return np.unique(np.sort(edges, axis=1), axis=0)


def _draw_projected_mesh(image: np.ndarray, vertices: np.ndarray, faces: np.ndarray,
                         calib: Calibration, side: str, scale: tuple[float, float]) -> None:
    xyz = np.asarray(vertices, dtype=np.float64).reshape(-1, 3)
    uv, valid = project_ds_radtan(xyz, calib)
    uv[:, 0] *= scale[0]
    uv[:, 1] *= scale[1]
    h, w = image.shape[:2]
    valid &= np.isfinite(uv).all(axis=1) & (np.abs(uv).max(axis=1) < 100_000)
    face_valid = valid[faces].all(axis=1)
    if not np.any(face_valid):
        return
    triangles = np.rint(uv[faces[face_valid]]).astype(np.int32).reshape(-1, 3, 1, 2)
    mask = np.zeros((h, w), dtype=np.uint8)
    cv2.fillPoly(mask, triangles, 255, lineType=cv2.LINE_AA)
    covered = mask > 0
    tint = np.asarray(MESH_COLORS[side], dtype=np.float32)
    # The overlay tint is 30%; retain 70% of the underlying image.
    image[covered] = np.clip(image[covered].astype(np.float32) * 0.70 + tint * 0.30, 0, 255).astype(np.uint8)

    edges = _mesh_edges(faces)
    edge_valid = valid[edges].all(axis=1)
    if np.any(edge_valid):
        lines = np.rint(uv[edges[edge_valid]]).astype(np.int32)
        contours = [line.reshape(2, 1, 2) for line in lines]
        edge_layer = image.copy()
        cv2.polylines(edge_layer, contours, False, MESH_COLORS[side], 1, cv2.LINE_AA)
        edge_mask = np.any(edge_layer != image, axis=2)
        image[edge_mask] = np.clip(
            image[edge_mask].astype(np.float32) * 0.70 + edge_layer[edge_mask].astype(np.float32) * 0.30,
            0, 255,
        ).astype(np.uint8)


